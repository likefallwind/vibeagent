LIST_FIELD_FAILURE_KINDS = {
    "read_files": "files",
    "read_file_contexts": "contexts",
    "output_contexts": "contexts",
    "read_file_ranges": "ranges",
    "file_info": "files",
    "image_info": "images",
    "python_symbols": "files",
    "code_outline": "files",
}


def is_failed_tool_result(result: dict[str, Any]) -> bool:
    kind = result.get("kind")
    if kind in {"tool_error", "approval_denied"}:
        return True
    if kind in OK_FIELD_FAILURE_KINDS:
        return result.get("ok") is False
    list_field = LIST_FIELD_FAILURE_KINDS.get(kind)
    if list_field:
        values = result.get(list_field)
        return isinstance(values, list) and any(isinstance(item, dict) and item.get("ok") is False for item in values)
    if kind == "run_command":
        command_result = result.get("result")
        if not isinstance(command_result, dict):
            return True
        return command_result.get("exit_code") != 0 or command_result.get("timed_out") is True
    if kind in {"run_commands", "run_suggested_checks"}:
        return result.get("ok") is False
    return False
